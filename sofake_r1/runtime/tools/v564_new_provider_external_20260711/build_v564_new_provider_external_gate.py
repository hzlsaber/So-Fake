LABELS = {0: "REAL", 1: "FULL_SYNTHETIC", 2: "TAMPERED"}
LABEL_TO_ID = {v: k for k, v in LABELS.items()}
ANSWER_RE = re.compile(r"<answer>\s*(REAL|FULL_SYNTHETIC|TAMPERED)\b", re.I)
THINK_RE = re.compile(r"<think>\s*(.*?)\s*</think>", re.I | re.S)
BOX_RE = re.compile(
    r"<\|box_start\|>\s*\(\s*[-+]?\d+(?:\.\d+)?\s*,\s*[-+]?\d+(?:\.\d+)?\s*\)\s*,"
    r"\s*\(\s*[-+]?\d+(?:\.\d+)?\s*,\s*[-+]?\d+(?:\.\d+)?\s*\)\s*<\|box_end\|>",
    re.I,
)

OBSERVER_PROMPT = (
    "<image>\n"
    "Please carefully describe the content of this image and classify its REAL, "
    "TAMPERED, or FULL_SYNTHETIC.\n"
    " DEFINITIONS: - REAL: The image is authentic with no AI generation or "
    "manipulation. - TAMPERED: Parts of the image have been manipulated, edited, "
    "or altered. - FULL_SYNTHETIC: The entire image was generated by AI.\n"
    "Output the thinking process in <think> </think> and final answer in "
    "<answer> </answer> tags.\n"
    "Additionally, if the image is TAMPERED, output the one bbox to depict the "
    "tampered area.\n"
    "i.e., <think> thinking process here </think>\n"
    "<answer>{Answer}</answer>"
)


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def write_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def norm_path(path: str) -> str:
    return os.path.realpath(os.path.expanduser(str(path)))


def label_name(value: Any) -> str:
    if isinstance(value, str):
        text = value.strip().upper()
        if text in LABEL_TO_ID:
            return text
        if text.isdigit():
            return LABELS.get(int(text), "UNKNOWN")
    if isinstance(value, int):
        return LABELS.get(value, "UNKNOWN")
    return "UNKNOWN"


def image_from_row(row: dict[str, Any]) -> str:
    images = row.get("images")
    if images:
        first = images[0]
        if isinstance(first, dict):
            return str(first.get("path") or "")
        return str(first)
    return str(row.get("image") or (row.get("meta") or {}).get("image") or (row.get("meta") or {}).get("image_path") or "")


def gt_from_sample(row: dict[str, Any]) -> str:
    return label_name(row.get("gt_cls", row.get("label", (row.get("meta") or {}).get("gt_label_name"))))


def make_observer_input(args: argparse.Namespace) -> None:
    rows = read_jsonl(args.samples)
    out: list[dict[str, Any]] = []
    for idx, row in enumerate(rows):
        image = str(row.get("image") or row.get("path") or row.get("image_path") or "")
        if not image:
            raise ValueError(f"missing image in sample row {idx}")
        gt = gt_from_sample(row)
        if gt == "UNKNOWN":
            raise ValueError(f"missing/unknown gt in sample row {idx}: {row}")
        sample_id = str(row.get("sample_id") or row.get("sid") or f"{args.dataset}_{idx:07d}")
        source = str(row.get("source") or row.get("subsource") or args.dataset)
        meta = {
            "sample_id": sample_id,
            "image": image,
            "rel_path": row.get("rel_path", ""),
            "binary_label": "REAL" if gt == "REAL" else "FAKE",
            "label": LABEL_TO_ID[gt],
            "label_name": gt,
            "source": source,
            "dataset": row.get("dataset", args.dataset),
            "subsource": row.get("subsource", ""),
        }
        out.append(
            {
                "messages": [
                    {"role": "user", "content": OBSERVER_PROMPT},
                    {"role": "assistant", "content": f"<answer>{gt}</answer>"},
                ],
                "images": [image],
                "label": LABEL_TO_ID[gt],
                "sample_id": sample_id,
                "meta": meta,
            }
        )
    write_jsonl(args.out, out)
    print(f"WROTE observer input: {args.out} rows={len(out)}")


def parse_observer(row: dict[str, Any]) -> dict[str, str]:
    response = str(row.get("response") or "")
    answer_match = ANSWER_RE.search(response)
    answer = answer_match.group(1).upper() if answer_match else label_name(row.get("label"))
    think_match = THINK_RE.search(response)
    report = " ".join((think_match.group(1) if think_match else response).strip().split())
    bbox_match = BOX_RE.search(response)
    bbox = bbox_match.group(0) if bbox_match and answer == "TAMPERED" else "NONE"
    if report:
        text = f"Observer answer is {answer}. {report}"
    else:
        text = f"Observer answer is {answer}."
    return {"answer": answer, "bbox": bbox, "report": text}


def load_observer_map(path: Path) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for row in read_jsonl(path):
        image = norm_path(image_from_row(row))
        if not image:
            continue
        parsed = parse_observer(row)
        parsed["image"] = image
        out[image] = parsed
    return out


def load_samples(path: Path) -> list[dict[str, Any]]:
    rows = read_jsonl(path)
    for idx, row in enumerate(rows):
        row.setdefault("sample_id", row.get("sid") or f"sample_{idx:07d}")
    return rows


def load_provider_raw(path: Path) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for row in read_jsonl(path):
        sid = str(row.get("sample_id") or row.get("sid") or "")
        image = norm_path(str(row.get("path") or row.get("image") or ""))
        if sid:
            out[f"sid::{sid}"] = row
        if image:
            out[f"image::{image}"] = row
    return out


def provider_raw_for(sample: dict[str, Any], raw_map: dict[str, dict[str, Any]]) -> dict[str, Any]:
    sid = str(sample.get("sample_id") or sample.get("sid") or "")
    image = norm_path(str(sample.get("image") or sample.get("path") or ""))
    row = raw_map.get(f"sid::{sid}") or raw_map.get(f"image::{image}")
    if row is None:
        raise KeyError(f"missing rerun provider row for sid={sid} image={image}")
    return row


def provider_meta_from_raw(raw: dict[str, Any]) -> dict[str, Any]:
    answer = str(raw.get("evidence_answer") or LABELS.get(int(raw.get("evidence_pred", -1)), "UNKNOWN")).upper()
    if answer not in LABEL_TO_ID:
        raise ValueError(f"bad provider answer from rerun evidence: {answer} row={raw}")
    return {
        "evidence_provider_answer": answer,
        "provider_pred3": int(raw.get("evidence_pred", LABEL_TO_ID[answer])),
        "provider_confidence": raw.get("evidence_confidence"),
        "provider_transform": raw.get("transform"),
        "provider_suspicion": raw.get("suspicion"),
        "provider_effective_s": raw.get("effective_s"),
        "provider_answer_source": "rerun_locked_provider_m60",
        "provider_no_old_answer": True,
    }


def build_source_row(
    sample: dict[str, Any],
    observer: dict[str, str],
    raw_provider: dict[str, Any],
    dataset: str,
    split: str,
) -> dict[str, Any]:
    image = str(sample.get("image") or sample.get("path") or "")
    gt = gt_from_sample(sample)
    meta = {
        "sample_id": str(sample.get("sample_id") or sample.get("sid")),
        "external_dataset": dataset,
        "external_split": split,
        "source": sample.get("source", ""),
        "subsource": sample.get("subsource", ""),
        "image_path": image,
        "gt_label_name": gt,
        "observer_answer": observer["answer"],
        "observer_bbox": observer["bbox"],
        "schema_version": "v564_new_provider_external_source_v1",
    }
    meta.update(provider_meta_from_raw(raw_provider))
    provider_seed = {
        "meta": meta,
        "images": [{"path": image}],
    }
    prov = v547.normalized_provider(provider_seed, raw_provider)
    meta.update(
        {
            "evidence_provider_answer": prov["answer"],
            "evidence_provider_bbox": prov["bbox"],
            "provider_support": prov["support"].lower(),
            "provider_evidence_class": prov["evidence_class"],
            "provider_descriptor_strength": prov["descriptor_strength"],
            "provider_confidence_level": prov["confidence_level"],
            "provider_raw_feta_pred": prov["raw_feta_pred"],
            "provider_locked_pred3": prov["locked_pred3"],
            "provider_logit_margin_proxy": prov["logit_margin_proxy"],
            "provider_descriptor_values": prov["descriptor_values"],
            "provider_compatible_evidence_path": raw_provider.get("path"),
        }
    )
    provider_assessment = prov["assessment"]
    content = f"""<image>
[Visual Observer Report]
observer_answer: {observer['answer']}
observer_bbox: {observer['bbox']}
observer_report: {observer['report']}

[Forensic Evidence Provider Report]
evidence_provider_answer: {prov['answer']}
evidence_provider_bbox: {prov['bbox']}
evidence_provider_assessment: {provider_assessment}
provider_support: {prov['support'].lower()}

[STEP 3: APPLY THE EVIDENCE GATE]
"""
    return {
        "messages": [{"role": "user", "content": content}],
        "images": [{"bytes": None, "path": image}],
        "label": LABEL_TO_ID[gt],
        "meta": meta,
    }


def selected_samples(samples: list[dict[str, Any]], split: str) -> list[dict[str, Any]]:
    if split == "bfree":
        return samples
    if split == "wildrf":
        return samples
    if split == "chameleon":
        return samples
    if split.startswith("aiginow_"):
        tail = split.removeprefix("aiginow_")
        if "_" not in tail:
            raise ValueError(f"bad AIGI-Now split: {split}")
        generator, subset = tail.rsplit("_", 1)
        source = f"{generator}/{subset}"
        return [row for row in samples if str(row.get("source")) == source]
    if not split.startswith("cospy_"):
        raise ValueError(f"unknown split: {split}")
    fake_source = split.removeprefix("cospy_")
    return [row for row in samples if str(row.get("source")) in {"real", fake_source}]


def build_dataset(
    *,
    dataset: str,
    samples_path: Path,
    observer_path: Path,
    provider_path: Path,
    splits: list[str],
    old_gate_dir: Path,
    phrase_dir: Path,
    tag: str,
) -> list[dict[str, Any]]:
    samples = load_samples(samples_path)
    observer_map = load_observer_map(observer_path)
    provider_map = load_provider_raw(provider_path)
    old_gate_dir.mkdir(parents=True, exist_ok=True)
    phrase_dir.mkdir(parents=True, exist_ok=True)

    source_summaries: list[dict[str, Any]] = []
    gate_summaries: list[dict[str, Any]] = []
    phrase_summaries: list[dict[str, Any]] = []
    for split in splits:
        rows: list[dict[str, Any]] = []
        counts = Counter()
        for sample in selected_samples(samples, split):
            image = norm_path(str(sample.get("image") or sample.get("path") or ""))
            obs = observer_map.get(image)
            if obs is None:
                counts["skipped:missing_observer"] += 1
                continue
            try:
                raw = provider_raw_for(sample, provider_map)
            except KeyError:
                counts["skipped:missing_provider"] += 1
                continue
            row = build_source_row(sample, obs, raw, dataset, split)
            rows.append(row)
            counts[f"gt:{row['meta']['gt_label_name']}"] += 1
            counts[f"observer:{row['meta']['observer_answer']}"] += 1
            counts[f"provider:{row['meta']['evidence_provider_answer']}"] += 1
            counts[f"source:{row['meta'].get('source')}"] += 1
            counts[f"provider_source:{row['meta']['provider_answer_source']}"] += 1
        source_path = old_gate_dir / f"{split}_new_provider_for_v5_51_gate.jsonl"
        write_jsonl(source_path, rows)
        gate_summary = build_split(source_path, old_gate_dir, split)
        gate_summaries.append(gate_summary)
        source_summaries.append(
            {
                "split": split,
                "dataset": dataset,
                "source_jsonl": str(source_path),
                "rows": len(rows),
                "counts": dict(counts),
            }
        )

    (old_gate_dir / "v5_51_new_provider_gate_aware_build_summary.md").write_text(
        render_report(gate_summaries), encoding="utf-8"
    )
    rules_blob = json.loads(RULES.read_text(encoding="utf-8"))
    rules = rules_blob["manual_plus_mined_clean"]
    for split in splits:
        phrase_summaries.append(phrase_build_split(old_gate_dir, split, phrase_dir, rules, tag))
    write_json(phrase_dir / "v5_60_new_provider_phrase_gate_build_summary_20260711.json", phrase_summaries)
    write_json(old_gate_dir / f"{dataset}_new_provider_source_summary_20260711.json", source_summaries)
    return source_summaries + phrase_summaries


